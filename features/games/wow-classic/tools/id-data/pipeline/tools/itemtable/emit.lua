local classify = dofile("tools/itemtable/classify.lua")
local M = { }
local HEADER = [[-- GENERATED by bin/generate-id-data. Do not edit.
--
-- Hand-editing this file is always a bug: the next regeneration discards it.
-- Sets are derived from game data by tools/id-data/pipeline/tools/itemtable/rules/, so a wrong entry
-- means a wrong RULE -- fix it there and regenerate.
]]
local quote
quote = function(s)
  return ('%q'):format(s)
end
local LIBRARY_FOR = {
  Spell = "idLibSpellTable-1.0",
  Talent = "idLibTalentTable-1.0"
}
local DEFAULT_LIBRARY = "idLibItemTable-1.0"
M.libraryFor = function(domain)
  return LIBRARY_FOR[domain] or DEFAULT_LIBRARY
end
M.domainChunk = function(domain, revision, result)
  local names
  do
    local _accum_0 = { }
    local _len_0 = 1
    for name in pairs(result.sets) do
      _accum_0[_len_0] = name
      _len_0 = _len_0 + 1
    end
    names = _accum_0
  end
  table.sort(names)
  local lines = {
    HEADER
  }
  lines[#lines + 1] = ('local lib = LibStub and LibStub("%s", true)'):format(M.libraryFor(domain))
  lines[#lines + 1] = "if not lib then return end"
  lines[#lines + 1] = ("lib:AddData(%s, %d, {"):format(quote(domain), revision)
  for _index_0 = 1, #names do
    local name = names[_index_0]
    local encoded = classify.encodeSet(result.sets[name])
    lines[#lines + 1] = ("  [%s] = %s,"):format(quote(name), quote(encoded))
  end
  lines[#lines + 1] = "})"
  return table.concat(lines, "\n") .. "\n"
end
M.manifestChunk = function(manifest, library)
  local keys
  do
    local _accum_0 = { }
    local _len_0 = 1
    for k in pairs(manifest) do
      _accum_0[_len_0] = k
      _len_0 = _len_0 + 1
    end
    keys = _accum_0
  end
  table.sort(keys)
  local lines = {
    HEADER
  }
  lines[#lines + 1] = ('local lib = LibStub and LibStub("%s", true)'):format((library or DEFAULT_LIBRARY))
  lines[#lines + 1] = "if not lib then return end"
  lines[#lines + 1] = "lib:AddManifest({"
  for _index_0 = 1, #keys do
    local k = keys[_index_0]
    local v = manifest[k]
    local rendered
    local _exp_0 = type(v)
    if "number" == _exp_0 then
      rendered = tostring(v)
    elseif "boolean" == _exp_0 then
      rendered = tostring(v)
    else
      rendered = quote(tostring(v))
    end
    lines[#lines + 1] = ("  [%s] = %s,"):format(quote(k), rendered)
  end
  lines[#lines + 1] = "})"
  return table.concat(lines, "\n") .. "\n"
end
M.dataXml = function(fileNames)
  local lines = {
    '<Ui xmlns="http://www.blizzard.com/wow/ui/">',
    "  <!-- GENERATED by bin/generate-id-data. Do not edit. -->"
  }
  for _index_0 = 1, #fileNames do
    local f = fileNames[_index_0]
    lines[#lines + 1] = ('  <Script file="%s"/>'):format(f)
  end
  lines[#lines + 1] = "</Ui>"
  return table.concat(lines, "\n") .. "\n"
end
local writeFile
writeFile = function(path, text)
  local fh, err = io.open(path, "w")
  if not (fh) then
    return nil, ("cannot write %s: %s"):format(path, tostring(err))
  end
  fh:write(text)
  fh:close()
  return true
end
M.writeAll = function(dirs, domains, manifest)
  if type(dirs) == "string" then
    dirs = {
      [DEFAULT_LIBRARY] = dirs
    }
  end
  local written, byLibrary = { }, { }
  local names
  do
    local _accum_0 = { }
    local _len_0 = 1
    for d in pairs(domains) do
      _accum_0[_len_0] = d
      _len_0 = _len_0 + 1
    end
    names = _accum_0
  end
  table.sort(names)
  for _index_0 = 1, #names do
    local domain = names[_index_0]
    local library = M.libraryFor(domain)
    local dir = dirs[library]
    if not (dir) then
      return nil, ("no output directory configured for %s"):format(library)
    end
    dir = dir:gsub("/$", "")
    local file = ("%s.lua"):format(domain)
    local entry = domains[domain]
    local ok, err = writeFile(("%s/%s"):format(dir, file), M.domainChunk(domain, entry.revision, entry.result))
    if not (ok) then
      return nil, err
    end
    local _update_0 = library
    byLibrary[_update_0] = byLibrary[_update_0] or { }
    byLibrary[library][#byLibrary[library] + 1] = file
    written[#written + 1] = ("%s/%s"):format(library, file)
  end
  for library, files in pairs(byLibrary) do
    local dir = dirs[library]:gsub("/$", "")
    local ok, err = writeFile(("%s/manifest.lua"):format(dir), M.manifestChunk(manifest, library))
    if not (ok) then
      return nil, err
    end
    local ordered = {
      "manifest.lua"
    }
    for _index_0 = 1, #files do
      local f = files[_index_0]
      ordered[#ordered + 1] = f
    end
    ok, err = writeFile(("%s/data.xml"):format(dir), M.dataXml(ordered))
    if not (ok) then
      return nil, err
    end
    written[#written + 1] = ("%s/manifest.lua"):format(library)
  end
  table.sort(written)
  return written
end
return M
